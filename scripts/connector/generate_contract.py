#!/usr/bin/env python3
"""Generate inert language tables from the reviewed connector operation inventory."""
import argparse
import hashlib
import json
import shutil
import subprocess
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "contracts/connector/v1/operations.json"


def outputs():
    raw = SOURCE.read_bytes()
    doc = json.loads(raw)
    if doc["version"] != 1 or doc["columns"] != [
        "operation", "destination", "capabilities", "delegationAllowed", "method", "route"
    ]:
        raise ValueError("invalid contract version or columns")
    entries = {}
    bindings = {}
    for op, dest, caps, allowed, method, route in doc["operations"]:
        if dest not in ("ttobak-api-bridge", "ttobak-qa-bridge"):
            raise ValueError("invalid destination")
        if not caps or "read" not in caps or caps != sorted(set(caps)):
            raise ValueError("invalid capability order")
        if not set(caps) <= {"read", "write", "share", "delete"}:
            raise ValueError("unknown capability")
        if type(allowed) is not bool or method not in ("GET", "POST", "PUT", "PATCH", "DELETE", "TOOL", "INTERNAL"):
            raise ValueError("invalid operation")
        value = (dest, ",".join(caps), allowed)
        if op in entries and entries[op] != value:
            raise ValueError("inconsistent operation bindings")
        entries[op] = value
        if dest == "ttobak-api-bridge":
            binding = (method, route)
            if binding in bindings and bindings[binding] != op:
                raise ValueError("ambiguous HTTP operation binding")
            bindings[binding] = op
    digest = hashlib.sha256(raw).hexdigest()
    notice = "Code generated by scripts/connector/generate_contract.py; DO NOT EDIT."
    groups = defaultdict(list)
    for op, rule in sorted(entries.items()):
        groups[rule].append(op)
    go = [f"// {notice}", "package connector", "", f'const ContractSHA256 = "{digest}"', "",
          "var operationRules = func() map[string]operationRule {",
          "out := make(map[string]operationRule)", "groups := map[operationRule][]string{"]
    ts = [f"// {notice}", f'export const CONTRACT_SHA256 = "{digest}";',
          "const groups: readonly (readonly [string, string, boolean, readonly string[]])[] = ["]
    py = [f"# {notice}", "from types import MappingProxyType", f'CONTRACT_SHA256 = "{digest}"',
          "OPERATION_RULES = MappingProxyType({op: (dest, caps, allowed)",
          "    for dest, caps, allowed, operations in ("]
    for (dest, caps, allowed), operations in sorted(groups.items()):
        go.append(f'{{"{dest}", "{caps}", {str(allowed).lower()}}}: {{')
        ts.append(f'  ["{dest}", "{caps}", {str(allowed).lower()}, [')
        py.append(f'        ("{dest}", "{caps}", {allowed}, (')
        for op in operations:
            go.append(f'"{op}",')
            ts.append(f'    "{op}",')
            py.append(f'            "{op}",')
        go.append("},")
        ts.append("  ]],")
        py.append("        )),")
    go.extend(["}", "for rule, operations := range groups {", "for _, op := range operations { out[op] = rule }",
               "}", "return out", "}()", ""])
    go.extend(["var httpOperationBindings = map[string]string{"])
    for (method, route), operation in sorted(bindings.items()):
        go.append(json.dumps(method + " " + route) + ": " + json.dumps(operation) + ",")
    go.extend(["}", ""])
    ts.extend(["];", "export const operationRules: Readonly<Record<string, readonly [string, string, boolean]>> =",
               "  Object.freeze(Object.fromEntries(groups.flatMap(([dest, caps, allowed, operations]) =>",
               "    operations.map(op => [op, Object.freeze([dest, caps, allowed] as const)]))));", ""])
    ts.append("export const httpOperationBindings: Readonly<Record<string, string>> = Object.freeze({")
    for (method, route), operation in sorted(bindings.items()):
        ts.append("  " + json.dumps(method + " " + route) + ": " + json.dumps(operation) + ",")
    ts.extend(["});", ""])
    py.extend(["    ) for op in operations})", ""])
    formatter = shutil.which("gofmt")
    if formatter is None:
        raise SystemExit("gofmt must be available on PATH")
    formatted = subprocess.run([formatter], input="\n".join(go), text=True, capture_output=True, check=True).stdout
    return {
        ROOT / "backend/internal/connector/operations_generated.go": formatted,
        ROOT / "mcp-server/src/connector-operations.ts": "\n".join(ts),
        ROOT / "backend/python/qa/connector_operations.py": "\n".join(py),
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, text in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f"generated connector table is stale: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)


if __name__ == "__main__":
    main()
