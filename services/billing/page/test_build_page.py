"""Tests for build_page.py. Run from services/billing/page after `npm ci`:
python3 -m unittest test_build_page -v"""
import os
import re
import subprocess
import sys
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
COMMITTED = os.path.join(REPO, "frontend", "public", "billing-app")
GENERATED = "<!-- GENERATED by services/billing/page/build_page.py; do not edit -->\n"
# files written from this directory's sources (the rest of the output is copied vendor code)
OWN = ["index.html", "upload.html", "dash-shim.js", "tokens.css"]


def build(out):
    subprocess.run([sys.executable, "-I", os.path.join(HERE, "build_page.py"), "--out", out],
                   check=True, capture_output=True)


def tree(root):
    found = {}
    for d, _, files in os.walk(root):
        for f in files:
            p = os.path.join(d, f)
            with open(p, "rb") as fh:
                found[os.path.relpath(p, root).replace(os.sep, "/")] = fh.read()
    return found


class BuildPageTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tmp = tempfile.TemporaryDirectory()
        cls.out = os.path.join(cls.tmp.name, "billing-app")
        build(cls.out)
        cls.files = tree(cls.out)
        cls.own = {k: cls.files[k].decode("utf-8") for k in OWN}

    @classmethod
    def tearDownClass(cls):
        cls.tmp.cleanup()

    def test_generated_output_is_current(self):
        committed = tree(COMMITTED)
        self.assertEqual(sorted(self.files), sorted(committed), "run python3 -I build_page.py")
        for k, v in self.files.items():
            self.assertEqual(v, committed[k], "%s is stale; run python3 -I build_page.py" % k)

    def test_html_carries_generated_header(self):
        for k in ("index.html", "upload.html"):
            self.assertTrue(self.own[k].startswith(GENERATED), k)

    def test_no_placeholders_or_login_links(self):
        for k, text in self.own.items():
            for bad in ("{{", "/login", "/static/", "/logout"):
                self.assertNotIn(bad, text, k)

    def test_api_paths_are_billing_scoped(self):
        for k, text in self.own.items():
            self.assertFalse(re.search(r"(?<!/api/billing/)api/data/", text), k)
            self.assertFalse(re.search(r"(?<![A-Za-z0-9_/])api/", text), "%s: relative api/ path" % k)
            self.assertFalse(re.search(r"/api/(?!billing/)", text), "%s: /api/ outside /api/billing/" % k)
            self.assertFalse(re.search(r"""['"]/upload(?![A-Za-z])""", text), "%s: /upload link" % k)

    def test_links_between_pages_are_relative(self):
        self.assertIn('href="upload.html"', self.own["index.html"])
        self.assertIn('href="index.html"', self.own["upload.html"])
        self.assertIn('<script src="dash-shim.js" data-auth-only></script>', self.own["upload.html"])
        self.assertNotIn("d3.min.js", self.own["upload.html"])

    def test_report_links_are_not_native_downloads(self):
        html = self.own["index.html"]
        for anchor in re.findall(r'<a id="(?:report-link|cur-report)"[^>]*>', html):
            self.assertNotIn("download", anchor)

    def test_assets_resolve(self):
        for k in ("index.html", "upload.html"):
            for ref in re.findall(r'(?:src|href)="([^"#?]+\.(?:js|css))"', self.own[k]):
                self.assertFalse(ref.startswith("/"), "%s: %s is not relative to /billing-app/" % (k, ref))
                self.assertIn(ref, self.files, "%s: %s missing" % (k, ref))
        css = self.files["vendor/pretendard/pretendardvariable-dynamic-subset.css"].decode("utf-8")
        fonts = set(re.findall(r"url\(\./([^)]+)\)", css))
        self.assertTrue(fonts)
        for f in fonts:
            self.assertIn("vendor/pretendard/" + f, self.files)
        extra = [k for k in self.files if k.endswith(".woff2") and k[len("vendor/pretendard/"):] not in fonts]
        self.assertEqual(extra, [], "only fonts referenced by the dynamic-subset CSS are copied")

    def test_vendor_files_are_unmodified(self):
        nm = os.path.join(HERE, "node_modules")
        with open(os.path.join(nm, "d3", "dist", "d3.min.js"), "rb") as fh:
            self.assertEqual(self.files["vendor/d3.min.js"], fh.read())


if __name__ == "__main__":
    unittest.main()
