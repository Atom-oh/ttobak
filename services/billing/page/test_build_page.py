"""Tests for build_page.py. Run from services/billing/page after `npm ci`:
python3 -m unittest test_build_page -v"""
import os
import re
import subprocess
import sys
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
GENERATED = "<!-- GENERATED by services/billing/page/build_page.py; do not edit -->\n"
# files written from this directory's sources (the rest of the output is copied vendor code)
OWN = ["index.html", "upload.html", "dash-shim.js", "tokens.css",
       "index.page.1.js", "index.page.2.js", "upload.page.1.js"]
JS_HEADER = "// GENERATED by services/billing/page/build_page.py; do not edit\n"


def build(out):
    subprocess.run([sys.executable, "-I", os.path.join(HERE, "build_page.py"), "--out", out],
                   check=True, capture_output=True)


def tree(root):
    found = {}
    for d, _, files in os.walk(root):
        for f in files:
            p = os.path.join(d, f)
            with open(p, "rb") as fh:
                found[os.path.relpath(p, root).replace(os.sep, "/")] = fh.read()
    return found


class BuildPageTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tmp = tempfile.TemporaryDirectory()
        cls.out = os.path.join(cls.tmp.name, "billing-app")
        build(cls.out)
        cls.files = tree(cls.out)
        cls.own = {k: cls.files[k].decode("utf-8") for k in OWN}

    @classmethod
    def tearDownClass(cls):
        cls.tmp.cleanup()

    def test_build_is_deterministic(self):
        # The output is not committed; every consumer regenerates it, so two
        # builds of the same sources must be byte-identical.
        with tempfile.TemporaryDirectory() as other:
            out = os.path.join(other, "billing-app")
            build(out)
            again = tree(out)
        self.assertEqual(sorted(again), sorted(self.files))
        for k, v in self.files.items():
            self.assertEqual(again[k], v, k)

    def test_expected_file_set(self):
        top = sorted(k for k in self.files if "/" not in k)
        self.assertEqual(top, sorted(OWN))
        vendor = sorted(k for k in self.files if k.startswith("vendor/")
                        and not k.startswith("vendor/pretendard/woff2-dynamic-subset/"))
        self.assertEqual(vendor, ["vendor/d3-LICENSE.txt", "vendor/d3.min.js",
                                  "vendor/pretendard/LICENSE.txt",
                                  "vendor/pretendard/pretendardvariable-dynamic-subset.css"])
        fonts = [k for k in self.files if k.startswith("vendor/pretendard/woff2-dynamic-subset/")]
        self.assertTrue(fonts)
        self.assertTrue(all(k.endswith(".woff2") for k in fonts), fonts)
        self.assertEqual(sorted(self.files), sorted(top + vendor + fonts))
        self.assertIn(b"Mike Bostock", self.files["vendor/d3-LICENSE.txt"])
        self.assertIn(b"SIL Open Font License", self.files["vendor/pretendard/LICENSE.txt"])

    def test_html_carries_generated_header(self):
        for k in ("index.html", "upload.html"):
            self.assertTrue(self.own[k].startswith(GENERATED), k)

    def test_no_inline_scripts(self):
        # The /billing-app/* CSP is script-src 'self': every script is an external file.
        for k in ("index.html", "upload.html"):
            tags = re.findall(r"<script\b[^>]*>", self.own[k], re.I)
            self.assertTrue(tags, k)
            for tag in tags:
                self.assertRegex(tag, r'\ssrc="[^"]+"', "%s: inline %s" % (k, tag))
            self.assertEqual(re.findall(r"<script\b[^>]*>([\s\S]*?)</script\s*>", self.own[k], re.I),
                             [""] * len(tags), k)
            self.assertNotRegex(self.own[k], r"\son[a-z]+\s*=", "%s: inline event handler" % k)

    def test_page_scripts_keep_source_order(self):
        def inline(src):
            with open(os.path.join(HERE, src), encoding="utf-8") as fh:
                return re.findall(r"<script>([\s\S]*?)</script\s*>", fh.read(), re.I)
        for page, src in (("index", "body.html"), ("upload", "upload.html")):
            bodies = inline(src)
            names = ["%s.page.%d.js" % (page, i + 1) for i in range(len(bodies))]
            refs = re.findall(r'<script src="(%s\.page\.\d+\.js)"></script>' % page, self.own[page + ".html"])
            self.assertEqual(refs, names)
            for name, body in zip(names, bodies):
                self.assertEqual(self.own[name], JS_HEADER + body)
            self.assertEqual(sorted(k for k in self.files if k.startswith(page + ".page.")), sorted(names))

    def test_no_placeholders_or_login_links(self):
        for k, text in self.own.items():
            for bad in ("{{", "/login", "/static/", "/logout"):
                self.assertNotIn(bad, text, k)

    def test_api_paths_are_billing_scoped(self):
        for k, text in self.own.items():
            self.assertFalse(re.search(r"(?<!/api/billing/)api/data/", text), k)
            self.assertFalse(re.search(r"(?<![A-Za-z0-9_/])api/", text), "%s: relative api/ path" % k)
            self.assertFalse(re.search(r"/api/(?!billing/)", text), "%s: /api/ outside /api/billing/" % k)
            self.assertFalse(re.search(r"""['"]/upload(?![A-Za-z])""", text), "%s: /upload link" % k)

    def test_links_between_pages_are_relative(self):
        self.assertIn('href="upload.html"', self.own["index.html"])
        self.assertIn('href="index.html"', self.own["upload.html"])
        self.assertIn('<script src="dash-shim.js" data-auth-only></script>', self.own["upload.html"])
        self.assertNotIn("d3.min.js", self.own["upload.html"])

    def test_report_links_are_not_native_downloads(self):
        html = self.own["index.html"]
        for anchor in re.findall(r'<a id="(?:report-link|cur-report)"[^>]*>', html):
            self.assertNotIn("download", anchor)

    def test_assets_resolve(self):
        for k in ("index.html", "upload.html"):
            for ref in re.findall(r'(?:src|href)="([^"#?]+\.(?:js|css))"', self.own[k]):
                self.assertFalse(ref.startswith("/"), "%s: %s is not relative to /billing-app/" % (k, ref))
                self.assertIn(ref, self.files, "%s: %s missing" % (k, ref))
        css = self.files["vendor/pretendard/pretendardvariable-dynamic-subset.css"].decode("utf-8")
        fonts = set(re.findall(r"url\(\./([^)]+)\)", css))
        self.assertTrue(fonts)
        for f in fonts:
            self.assertIn("vendor/pretendard/" + f, self.files)
        extra = [k for k in self.files if k.endswith(".woff2") and k[len("vendor/pretendard/"):] not in fonts]
        self.assertEqual(extra, [], "only fonts referenced by the dynamic-subset CSS are copied")

    def test_externalize_is_case_insensitive(self):
        sys.path.insert(0, HERE)
        try:
            import build_page
        finally:
            sys.path.remove(HERE)
        body, scripts = build_page.externalize("x", "<SCRIPT>a()</SCRIPT ><p></p>")
        self.assertEqual(body, '<script src="x.page.1.js"></script><p></p>')
        self.assertIn(b"a()", scripts["x.page.1.js"])
        with self.assertRaises(SystemExit):
            build_page.externalize("x", '<SCRIPT type="module">b()</SCRIPT>')

    def test_vendor_files_are_unmodified(self):
        nm = os.path.join(HERE, "node_modules")
        with open(os.path.join(nm, "d3", "dist", "d3.min.js"), "rb") as fh:
            self.assertEqual(self.files["vendor/d3.min.js"], fh.read())


if __name__ == "__main__":
    unittest.main()
