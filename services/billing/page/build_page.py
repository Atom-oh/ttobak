"""Build the Billing dashboard pages as same-origin static assets.
Usage (after `npm ci` in this directory): python3 -I build_page.py [--out DIR]
Writes DIR (default frontend/public/billing-app/, served at /billing-app/):
  index.html, upload.html  body.html / upload.html wrapped in a standalone shell (generated)
  index.page.N.js, upload.page.N.js  each page's inline <script> blocks, moved out in order
                           so the CSP needs no inline script (script-src 'self')
  dash-shim.js, tokens.css copied from this directory with a GENERATED header
  vendor/                  d3 and the Pretendard dynamic-subset CSS + its fonts, copied unchanged
The pages run inside the TTOBAK /billing page's iframe: no cookies, no server-injected
accounts or user; dash-shim.js gets a Bearer token from the parent window.
Every asset URL is relative to /billing-app/."""
import argparse
import html
import os
import re
import shutil

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
NM = os.path.join(HERE, "node_modules")
PRETENDARD = os.path.join(NM, "pretendard", "dist", "web", "variable")
SUBSET_CSS = "pretendardvariable-dynamic-subset.css"
GENERATED = "GENERATED by services/billing/page/build_page.py; do not edit"
TITLE = "AWS 빌링 인사이트"

PAGES = {
    # out name: (source body, title, extra head, bar link)
    "index.html": ("body.html", TITLE,
                   '<script src="vendor/d3.min.js"></script>\n<script src="dash-shim.js"></script>\n',
                   '<a href="upload.html">업로드</a>'),
    "upload.html": ("upload.html", "데이터 업로드 · " + TITLE,
                    '<script src="dash-shim.js" data-auth-only></script>\n',
                    '<a href="index.html">대시보드</a>'),
}

HEAD = """<!-- %s -->
<!doctype html>
<html lang="ko"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>%s</title>
<link rel="stylesheet" href="vendor/pretendard/%s">
<link rel="stylesheet" href="tokens.css">
%s</head><body>
<div class="app-bar"><span>AWS 빌링 인사이트 · 내부용 · %s</span></div>
<div id="dash-root">
"""
TAIL = "\n</div></body></html>\n"
INLINE_SCRIPT = re.compile(r"<script>(.*?)</script>", re.S)


def externalize(stem, body):
    """Move each inline <script> of body into stem.page.N.js, referenced by a classic
    <script src> at the same position (same order, same parser-blocking execution)."""
    scripts = {}

    def move(m):
        name = "%s.page.%d.js" % (stem, len(scripts) + 1)
        scripts[name] = ("// %s\n" % GENERATED + m.group(1)).encode("utf-8")
        return '<script src="%s"></script>' % name

    body = INLINE_SCRIPT.sub(move, body)
    if re.search(r"<script(?![^>]*\ssrc=)[^>]*>", body):
        raise SystemExit("%s: unsupported inline <script> form" % stem)
    return body, scripts


def read(path, mode="r"):
    with open(path, mode, **({} if "b" in mode else {"encoding": "utf-8"})) as fh:
        return fh.read()


def outputs():
    """{relative path: bytes} of the whole output directory."""
    out = {}
    for name, (src, title, extra, link) in PAGES.items():
        body, scripts = externalize(name[:-len(".html")], read(os.path.join(HERE, src)))
        page = HEAD % (GENERATED, html.escape(title), SUBSET_CSS, extra, link) + body + TAIL
        out[name] = page.encode("utf-8")
        out.update(scripts)
    out["dash-shim.js"] = ("// %s\n" % GENERATED + read(os.path.join(HERE, "dash-shim.js"))).encode("utf-8")
    out["tokens.css"] = ("/* %s */\n" % GENERATED + read(os.path.join(HERE, "tokens.css"))).encode("utf-8")
    out["vendor/d3.min.js"] = read(os.path.join(NM, "d3", "dist", "d3.min.js"), "rb")
    out["vendor/d3-LICENSE.txt"] = read(os.path.join(NM, "d3", "LICENSE"), "rb")
    css = read(os.path.join(PRETENDARD, SUBSET_CSS), "rb")
    out["vendor/pretendard/" + SUBSET_CSS] = css
    out["vendor/pretendard/LICENSE.txt"] = read(os.path.join(NM, "pretendard", "dist", "LICENSE.txt"), "rb")
    # only the fonts the dynamic-subset CSS references
    for font in sorted(set(re.findall(rb"url\(\./([^)]+)\)", css))):
        rel = font.decode("ascii")
        if ".." in rel.split("/"):
            raise SystemExit("unexpected font path " + rel)
        out["vendor/pretendard/" + rel] = read(os.path.join(PRETENDARD, rel), "rb")
    return out


def write(dest, files):
    if os.path.isdir(dest) and os.listdir(dest):
        index = os.path.join(dest, "index.html")
        if not os.path.isfile(index) or GENERATED not in read(index).split("\n", 1)[0]:
            raise SystemExit("refusing to overwrite %s: not a build_page.py output" % dest)
        shutil.rmtree(dest)
    for rel, data in files.items():
        path = os.path.join(dest, *rel.split("/"))
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "wb") as fh:
            fh.write(data)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("--out", default=os.path.join(REPO, "frontend", "public", "billing-app"))
    a = ap.parse_args()
    files = outputs()
    write(a.out, files)
    print("wrote", a.out, len(files), "files")


if __name__ == "__main__":
    main()
